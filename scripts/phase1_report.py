"""Generate reports/phase1_report.md from the dev-seed database. Every number in the report comes from this script.

    python scripts/phase1_report.py [--seed 1]
"""
import argparse
import json
import sqlite3
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.data.availability import set_as_of  # noqa: E402
from src.data.calendar import day_to_date  # noqa: E402
from src.data.metrics import cohort_metrics, retention_curve, store_fee  # noqa: E402
from src.generator.intents import compute_intent_metrics, evaluate_intents, load_scenarios  # noqa: E402

START = "2025-01-06"
CHANNELS = ["meta", "google_uac", "applovin", "unity", "tiktok", "organic"]


def md(df: pd.DataFrame, floats=4) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = [f"{v:.{floats}f}" if isinstance(v, float) else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def q(conn, sql, *args):
    return conn.execute(sql, args).fetchone()[0]


def sample_calculation(conn, channel, install_day, as_of_day, title):
    """Recompute one cohort's D3 metrics by hand from the visible views and compare with cohort_metrics."""
    as_of, install = day_to_date(START, as_of_day), day_to_date(START, install_day)
    fee = store_fee(conn)
    set_as_of(conn, as_of)
    where = f"channel = '{channel}' AND install_date = '{install}'"
    installs = q(conn, f"SELECT COUNT(*) FROM v_players WHERE {where}")
    active_d1 = q(conn, f"SELECT COUNT(*) FROM v_player_days WHERE {where} AND day_n = 1")
    gross = q(conn, f"SELECT COALESCE(SUM(iap_gross),0) FROM v_player_days WHERE {where} AND day_n <= 3")
    ad = q(conn, f"SELECT COALESCE(SUM(ad_revenue),0) FROM v_player_days WHERE {where} AND day_n <= 3")
    rows = q(conn, f"SELECT COUNT(*) FROM v_player_days WHERE {where} AND day_n <= 3")
    payers = q(conn, f"SELECT COUNT(DISTINCT player_id) FROM v_player_days WHERE {where} AND day_n <= 3 AND iap_gross > 0")
    spend = q(conn, f"SELECT spend FROM v_spend WHERE channel = '{channel}' AND spend_date = '{install}'")
    complete = q(conn, f"SELECT COUNT(*) FROM v_cohort_reporting WHERE {where} AND through_day = 3")
    sql_row = cohort_metrics(conn, as_of).query("channel == @channel and install_date == @install").iloc[0]
    out = [f"### {title}", "",
           f"Cohort: `{channel}` installed {install} (day {install_day}); review as-of {as_of} (day {as_of_day}); D3 milestone complete: {'yes' if complete else 'NO'}.", ""]
    out.append(f"- installed players reported: {installs}; spend: {spend:.2f}")
    if complete:
        out += [
            f"- CPI = spend / installs = {spend:.2f} / {installs} = {spend / installs:.4f}  (SQL: {sql_row.cpi:.4f})",
            f"- D1 retention = players with a day-1 row / ALL installed players = {active_d1} / {installs} = {active_d1 / installs:.4f}  (SQL: {sql_row.d1_retention:.4f})",
            f"- D0-D3 gross IAP = {gross:.2f}; ad revenue = {ad:.4f}; net = {gross:.2f} x (1 - {fee}) + {ad:.4f} = {gross * (1 - fee) + ad:.4f}  (SQL: {sql_row.d0_3_net_revenue:.4f})",
            f"- payer rate (D0-D3) = {payers} / {installs} = {payers / installs:.4f}  (SQL: {sql_row.payer_rate_d0_3:.4f})",
            f"- ARPDAU (D0-D3) = net / active player-days = {gross * (1 - fee) + ad:.4f} / {rows} = {(gross * (1 - fee) + ad) / rows:.4f}  (SQL: {sql_row.arpdau_d0_3:.4f})",
        ]
    else:
        out += [f"- D3 metrics are NULL in SQL by design (SQL: cpi={sql_row.cpi}, d0_3_net_revenue={sql_row.d0_3_net_revenue}).",
                f"- the raw visible D0-D3 net revenue so far would be {gross * (1 - fee) + ad:.4f} from {rows} visible player-days: a partial number that must not be used."]
    return "\n".join(out) + "\n"


def main(seed):
    db_dir = ROOT / "data" / "decision" / f"seed_{seed}"
    gen = json.loads((db_dir / "generation_report.json").read_text())
    conn = sqlite3.connect(db_dir / "decision.db")
    hidden = json.loads((ROOT / "data" / "hidden" / f"seed_{seed}" / "hidden_truth.json").read_text())

    L = ["# Phase 1 report (generated by scripts/phase1_report.py)", "",
         "ALL DATA IS SYNTHETIC. Money is synthetic USD. Dev seed only; held-out seeds have not been generated.", ""]
    L += ["## Generation run", "",
          f"- seed {gen['seed']}, install_scale {gen['install_scale']}",
          f"- generate: {gen['generate_seconds']} s; load into SQLite: {gen['load_seconds']} s",
          f"- database size: {gen['db_size_mb']} MB", "",
          md(pd.DataFrame([{"table": k, "rows": f"{v:,}"} for k, v in gen["row_counts"].items()])), ""]

    sizes = pd.read_sql_query("SELECT channel, install_date, COUNT(*) AS n FROM players GROUP BY 1, 2", conn)
    spend = pd.read_sql_query("SELECT channel, AVG(spend) AS mean_daily_spend FROM spend_daily GROUP BY 1", conn)
    by = sizes.groupby("channel").n.agg(["median", "min", "max", "sum"]).reset_index()
    by.columns = ["channel", "median installs/cohort-day", "min", "max", "total installs"]
    by = by.merge(spend, on="channel", how="left")
    L += ["## Cohort sizes (all days)", "", md(by, floats=1), ""]

    L += ["## Sample cohort calculations", "",
          sample_calculation(conn, "meta", 112, 245, "A. Ordinary cohort, recomputed by hand"),
          sample_calculation(conn, "unity", 293, 301, "B. Delayed-reporting trap: cohort not yet complete"),
          sample_calculation(conn, "google_uac", 298, 322, "C. Tracking outage cohort (installs normal, events collapsed)"),
          sample_calculation(conn, "google_uac", 286, 322, "C-control. Same channel, cohort before the outage"),
          sample_calculation(conn, "tiktok", 312, 322, "D. Tiny cohort with one whale"),
          sample_calculation(conn, "tiktok", 305, 322, "D-control. Same channel, ordinary cohort")]

    as_of = day_to_date(START, 245)
    curves = {}
    used = {}
    for ch in CHANNELS:
        c = retention_curve(conn, as_of, ch).set_index("day_n")
        curves[ch] = c.retention
        used[ch] = int(c.installs.iloc[0])
    days = [0, 1, 2, 3, 7, 14, 21, 30]
    table = pd.DataFrame({ch: [curves[ch].get(d, float("nan")) for d in days] for ch in CHANNELS}, index=[f"D{d}" for d in days]).reset_index(names="day")
    L += ["## Retention curves (classic: share of ALL installed players active on exactly day n)", "",
          f"As of {as_of} (day 245), over cohorts whose D30 milestone is complete; installs in denominator: "
          + ", ".join(f"{ch} {used[ch]:,}" for ch in CHANNELS) + ".", "", md(table), ""]

    metrics = compute_intent_metrics(conn, hidden)
    summ = pd.DataFrame([{"channel": ch, "avg D30 ROAS": s["avg_roas"], "target D30 ROAS": s["target"], "D180/D30": 1 / s["target"],
                          "D30/D3": s["mult"], "D3 net/install": s["d3_per_install"], "D30 net/install": s["v_ref"]}
                         for (sid, ch), s in metrics.items() if sid == "_summary"])
    L += ["## Per paid channel economics (generator QA, cohorts installed days 0..184; uses full stored data)", "", md(summ, 3), ""]
    rows = evaluate_intents(metrics, load_scenarios())
    L += ["## Generator QA: scenario calibration intents (thresholds committed before generation; checked against the dev seed)", "",
          "This is generator QA, not model or agent evidence. The generator was calibrated after a first dev run in which 4 of 17 intents "
          "failed, and one intent's cohort window was amended (both disclosed in the Phase 1 commit and in "
          "`evals/scenarios/delayed_reporting.json`). `true_step20_marginal_roas_over_target` is an approximate calibration proxy "
          "(value per install assumed proportional to player quality), not exact simulation truth, and is never an experiment-scoring oracle.", "",
          md(pd.DataFrame([{"scenario": r[0], "metric": r[1], "value": r[2], "must be": f"{r[3]} {r[4]}", "result": "PASS" if r[5] else "FAIL"} for r in rows]), 3),
          "", f"{sum(r[-1] for r in rows)}/{len(rows)} generator-QA checks satisfied.", ""]
    out = ROOT / "reports" / "phase1_report.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--seed", type=int, default=1)
    main(p.parse_args().seed)
